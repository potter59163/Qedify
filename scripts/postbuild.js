/**
 * Runs after `expo export`.
 *
 * 1. Static hosts serve /404.html for unknown URLs, so publish the app's own
 *    not-found page under that name.
 * 2. Write dist/sw.js, a service worker that precaches every published file,
 *    so the app keeps working on a slow or dropped connection (paper A2.4).
 */
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const dist = path.join(__dirname, "..", "dist");
const notFound = path.join(dist, "+not-found.html");

if (fs.existsSync(notFound)) {
  fs.copyFileSync(notFound, path.join(dist, "404.html"));
  console.log("postbuild: wrote dist/404.html");
} else {
  console.warn("postbuild: dist/+not-found.html is missing; no 404.html written");
}

function walk(dir, base = "") {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = base ? `${base}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...walk(path.join(dir, entry.name), rel));
    else out.push(rel);
  }
  return out;
}

// The Thai landing page is pre-rendered in Thai, so its document language must say so.
const thai = path.join(dist, "th.html");
if (fs.existsSync(thai)) {
  const html = fs.readFileSync(thai, "utf8");
  fs.writeFileSync(thai, html.replace(/<html(\s+)lang="en"/, '<html$1lang="th"'));
  console.log("postbuild: set lang=th on dist/th.html");
}

// Route-group copies such as (game)/home.html duplicate the public URLs, so they are not precached.
const SKIP = /(^|\/)(sw\.js|404\.html|\+not-found\.html|_sitemap\.html|robots\.txt|sitemap\.xml)$|\.map$|\(/;
const files = walk(dist).filter((f) => !SKIP.test(f)).sort();

// Pages are published with clean URLs: home.html is served at /home.
const urls = files.map((f) => {
  if (!f.endsWith(".html")) return `/${f}`;
  const page = f.replace(/(^|\/)index\.html$/, "$1").replace(/\.html$/, "");
  return `/${page}`.replace(/\/$/, "") || "/";
});

const hash = crypto.createHash("sha256");
for (const f of files) hash.update(f).update(fs.readFileSync(path.join(dist, f)));
const version = hash.digest("hex").slice(0, 12);

const sw = `// Generated by scripts/postbuild.js. Do not edit.
const CACHE = "qedify-${version}";
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      // One file failing must not stop the rest from being cached.
      .then((cache) => Promise.allSettled(PRECACHE.map((url) => cache.add(url))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("qedify-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  // The AI coach and anything on another origin always go to the network.
  if (url.origin !== self.location.origin || url.pathname.startsWith("/api/")) return;

  if (req.mode === "navigate") {
    // Network first, so a new deployment shows up at once; the cached page keeps the app usable offline.
    event.respondWith(
      fetch(req)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((cache) => cache.put(url.pathname, copy));
          }
          return res;
        })
        .catch(() => caches.match(url.pathname, { ignoreSearch: true }).then((hit) => hit || caches.match("/"))),
    );
    return;
  }

  // Scripts, fonts and images are fingerprinted or change only with a deployment: cache first.
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok && res.type === "basic") {
            const copy = res.clone();
            caches.open(CACHE).then((cache) => cache.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;

fs.writeFileSync(path.join(dist, "sw.js"), sw);
console.log(`postbuild: wrote dist/sw.js (${urls.length} files precached, version ${version})`);
